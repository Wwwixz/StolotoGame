package ru.stoloto.quickgame.domain;

/** Жизненный цикл комнаты. */
public enum RoomStatus {
    /** Ожидание игроков: идёт таймер, можно войти, докупить буст, выйти. */
    OPEN,
    /** Розыгрыш: победитель уже определён backend-логикой, идёт визуальная трансляция. */
    RUNNING,
    /** Раунд завершён, выплаты произведены. */
    FINISHED,
    /** Комната закрыта администратором (участникам OPEN-комнаты возвращается резерв). */
    CLOSED
}
